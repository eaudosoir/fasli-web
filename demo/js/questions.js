const QB = {
  custom() { return App.S.qbank || {}; },
  list(grade, week) {
    const own = (this.custom()[grade]?.[week] || []).map(x => [x[0], x[1], true]);
    const base = (QBANK[grade]?.[week] || []);
    return [...own, ...base];
  },
  /* أسئلة الدرس الحالي للفصل؛ وإن لم توجد فالأسئلة العامة */
  forClass(classId, week) {
    const c = App.cls[classId]; if (!c) return { week: 0, items: QBANK.general };
    const w = week || Curr.lesson(classId)?.week || Curr.lastDone(classId) + 1;
    const items = this.list(c.grade, w);
    return { week: w, items: items.length ? items : QBANK.general, general: !items.length };
  },
  async add(grade, week, q, a) {
    const all = JSON.parse(JSON.stringify(this.custom()));
    ((all[grade] ||= {})[week] ||= []).push([q, a]);
    await App.set('qbank', all);
  },
  async remove(grade, week, q) {
    const all = JSON.parse(JSON.stringify(this.custom()));
    if (all[grade]?.[week]) all[grade][week] = all[grade][week].filter(x => x[0] !== q);
    await App.set('qbank', all);
  }
};
